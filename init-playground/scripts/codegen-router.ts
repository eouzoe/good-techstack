/// <reference lib="ESNext" />

import { Glob, write } from 'bun';

interface ProcedureModule {
  exportName: string;
  fileName: string;
  filePath: string;
  namespace: string;
}

interface NamespaceRouterContext {
  conflicts: Set<string>;
  namespace: string;
  sorted: ProcedureModule[];
}

const PROCEDURES_GLOB = 'src/procedures/**/*.ts';
const PROCEDURES_PREFIX = 'src/procedures/';
const ROOT_NAMESPACE = '__root__';

const upperFirst = (word: string): string => word.charAt(0).toUpperCase() + word.slice(1);

const toCamel = (str: string): string =>
  str
    .split(/[-_/]/u)
    .map((segment, index) => {
      if (index === 0) {
        return segment;
      }
      return upperFirst(segment);
    })
    .join('');

const findConflicts = (modules: ProcedureModule[]): Set<string> => {
  const seen = new Set<string>();
  const conflicts = new Set<string>();
  for (const mod of modules) {
    if (seen.has(mod.exportName)) {
      conflicts.add(mod.exportName);
    }
    seen.add(mod.exportName);
  }
  return conflicts;
};

const importPathFor = (mod: ProcedureModule): string => {
  const { fileName, namespace } = mod;
  let path = '../procedures';
  if (namespace) {
    path += `/${namespace}`;
  }
  return `${path}/${fileName}`;
};

const aliasFor = (mod: ProcedureModule, conflicts: Set<string>): string => {
  if (!conflicts.has(mod.exportName)) {
    return '';
  }
  return ` as ${mod.namespace.replaceAll(/[/-]/gu, '_')}_${mod.exportName}`;
};

const header = (lines: string[]): void => {
  lines.push(
    '//',
    '// Auto-generated by scripts/codegen-router.ts',
    '// Do not edit by hand',
    '//',
    '',
  );
};

const scanProcedures = async (baseDir: string): Promise<ProcedureModule[]> => {
  const glob = new Glob(PROCEDURES_GLOB);
  const modules: ProcedureModule[] = [];

  for await (const file of glob.scan(baseDir)) {
    const relative = file.replace(PROCEDURES_PREFIX, '').replace(/\.ts$/u, '');
    const parts = relative.split('/');
    const fileName = parts.pop()!;
    const exportName = toCamel(fileName);
    const namespace = parts.join('/');

    modules.push({ exportName, fileName, filePath: file, namespace });
  }

  return modules;
};

const groupByNamespace = (modules: ProcedureModule[]): Map<string, ProcedureModule[]> => {
  const groups = new Map<string, ProcedureModule[]>();

  for (const mod of modules) {
    const { namespace } = mod;
    const key = namespace || ROOT_NAMESPACE;
    if (!groups.has(key)) {
      groups.set(key, []);
    }
    groups.get(key)!.push(mod);
  }

  return groups;
};

const writeImports = (lines: string[], context: NamespaceRouterContext): void => {
  const entries = context.sorted.map((mod) => ({
    line: `import { ${mod.exportName}${aliasFor(mod, context.conflicts)} } from '${importPathFor(mod)}';`,
    path: importPathFor(mod),
  }));
  entries.push({ line: "import { os } from '../server/os';", path: '../server/os' });
  entries.sort((left, right) => left.path.localeCompare(right.path));
  for (const entry of entries) {
    lines.push(entry.line);
  }
  lines.push('');
};

const routerMemberLine = (mod: ProcedureModule, conflicts: Set<string>): string => {
  if (conflicts.has(mod.exportName)) {
    const alias = `${mod.namespace.replaceAll(/[/-]/gu, '_')}_${mod.exportName}`;
    return `  ${mod.exportName}: ${alias},`;
  }
  return `  ${mod.exportName},`;
};

const writeRouterBody = (lines: string[], context: NamespaceRouterContext): void => {
  const { conflicts, namespace, sorted } = context;
  if (namespace === ROOT_NAMESPACE) {
    lines.push('export default os.router({');
  } else {
    lines.push(`export default os.${toCamel(namespace)}.router({`);
  }
  for (const mod of sorted) {
    lines.push(routerMemberLine(mod, conflicts));
  }
  lines.push('});', '');
};

const routerFileName = (namespace: string): string => {
  if (namespace === ROOT_NAMESPACE) {
    return '__root__';
  }
  return toCamel(namespace);
};

const generateNamespaceRouter = async (
  namespace: string,
  modules: ProcedureModule[],
  baseDir: string,
): Promise<void> => {
  const lines: string[] = [];
  const context: NamespaceRouterContext = {
    conflicts: findConflicts(modules),
    namespace,
    sorted: modules.toSorted((left, right) => left.exportName.localeCompare(right.exportName)),
  };

  header(lines);
  writeImports(lines, context);
  writeRouterBody(lines, context);

  const outPath = `${baseDir}/src/routers/${routerFileName(namespace)}.ts`;
  await write(outPath, lines.join('\n'));
  console.log(`wrote ${modules.length} procedures to ${outPath}`);
};

const writeAppRouterImports = (lines: string[], namespaces: string[]): void => {
  lines.push("import { os } from '../server/os';");
  if (namespaces.includes(ROOT_NAMESPACE)) {
    lines.push("import rootRouter from './__root__';");
  }
  lines.push('');
};

const writeAppRouterMembers = (lines: string[], namespaces: string[]): void => {
  for (const ns of namespaces) {
    const nsKey = toCamel(ns);
    if (ns === ROOT_NAMESPACE) {
      lines.push('  ...rootRouter,');
    } else {
      lines.push(`  ${nsKey}: os.${nsKey}.lazy(() => import('./${nsKey}')),`);
    }
  }
};

const writeEmptyAppRouter = async (outPath: string): Promise<void> => {
  const lines: string[] = [];
  header(lines);
  writeAppRouterImports(lines, []);
  lines.push(
    'export const appRouter = os.router({});',
    'export type AppRouter = typeof appRouter;',
    '',
  );
  await write(outPath, lines.join('\n'));
};

const buildAppRouterLines = (namespaces: string[]): string[] => {
  const lines: string[] = [];
  header(lines);
  writeAppRouterImports(lines, namespaces);
  lines.push('export const appRouter = os.router({');
  writeAppRouterMembers(lines, namespaces);
  lines.push('});', 'export type AppRouter = typeof appRouter;', '');
  return lines;
};

const generateAppRouter = async (namespaces: string[], baseDir: string): Promise<void> => {
  const outPath = `${baseDir}/src/routers/_app.ts`;
  if (namespaces.length === 0) {
    await writeEmptyAppRouter(outPath);
    return;
  }

  const lines = buildAppRouterLines(namespaces);
  await write(outPath, lines.join('\n'));
  console.log(`wrote ${namespaces.length} namespaces to ${outPath}`);
};

const logNoProcedures = (): void => {
  console.log('no procedure files found under src/procedures/');
  console.log('create a file like src/procedures/feature/list.ts to get started');
};

const expectedRouterFiles = (namespaces: string[]): Set<string> =>
  new Set(namespaces.map((ns) => routerFileName(ns)));

const isStaleRouter = (name: string, expected: Set<string>): boolean => {
  if (name === '_app') {
    return false;
  }
  return !expected.has(name);
};

const removeIfStale = async (file: string, expected: Set<string>): Promise<void> => {
  const name = file.replace('src/routers/', '').replace(/\.ts$/u, '');
  if (isStaleRouter(name, expected)) {
    const { unlink } = await import('node:fs/promises');
    await unlink(file);
    console.log(`removed stale router ${file}`);
  }
};

const removeStaleRouters = async (baseDir: string, namespaces: string[]): Promise<void> => {
  const expected = expectedRouterFiles(namespaces);
  const glob = new Glob('src/routers/*.ts');
  for await (const file of glob.scan(baseDir)) {
    await removeIfStale(file, expected);
  }
};

const generateAll = async (
  baseDir: string,
  namespaces: string[],
  groups: Map<string, ProcedureModule[]>,
): Promise<void> => {
  await Promise.all(namespaces.map((ns) => generateNamespaceRouter(ns, groups.get(ns)!, baseDir)));
  await removeStaleRouters(baseDir, namespaces);
  await generateAppRouter(namespaces, baseDir);
};

const main = async (): Promise<void> => {
  const baseDir = process.cwd();
  const modules = await scanProcedures(baseDir);

  if (modules.length === 0) {
    logNoProcedures();
    return;
  }

  const groups = groupByNamespace(modules);
  const sortedNamespaces = [...groups.keys()].toSorted();

  await generateAll(baseDir, sortedNamespaces, groups);
  console.log(`scanned ${modules.length} procedures across ${sortedNamespaces.length} namespaces`);
};

await main();
